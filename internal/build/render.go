// kv is one ordered output key. Values are string, bool, int, float64,
// []string, []any (from static), or boolMap (tools in map style).
type kv struct {
	K string
	V any
}

type boolMap []struct {
	K string
	V bool
}

func renderAgent(reg *config.Registry, h config.Harness, sel verify.Selected) ([]byte, error) {
	a := sel.Agent
	f := h.Agents.Fields

	var pairs []kv
	add := func(k string, v any) {
		if k != "" {
			pairs = append(pairs, kv{k, v})
		}
	}
	add(f.Name, a.Name)
	add(f.Description, a.Description)
	if model, effort := modelValues(f, sel); model != "" {
		add(f.Model, model)
		if effort != "" {
			add(f.Effort, effort)
		}
	} else if effort != "" {
		add(f.Effort, effort)
	}
	if f.Tools != nil && !a.InheritsAll() {
		add(f.Tools.Key, toolsValue(reg, h, a, f.Tools.Style))
	}
	if f.Skills != "" && len(a.Skills) > 0 {
		add(f.Skills, append([]string(nil), a.Skills...))
	}
	keys := make([]string, 0, len(h.Agents.Static))
	for k := range h.Agents.Static {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		add(k, h.Agents.Static[k])
	}
	for _, d := range h.Agents.Derived {
		hit := false
		for _, c := range d.IfAny {
			if a.HasCap(c) {
				hit = true
				break
			}
		}
		if hit {
			add(d.Key, d.Then)
		} else if d.Else != nil {
			add(d.Key, d.Else)
		}
	}

	switch h.Agents.Format {
	case "markdown":
		fm, err := yamlFrontmatter(pairs)
		if err != nil {
			return nil, err
		}
		return []byte("---\n" + fm + "---\n\n" + a.Body), nil
	case "toml":
		var b strings.Builder
		b.WriteString("# Generated by crewfile from " + a.Path + " — edit the source, not this file.\n")
		for _, p := range pairs {
			v, err := tomlValue(p.V)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", p.K, err)
			}
			fmt.Fprintf(&b, "%s = %s\n", tomlKey(p.K), v)
		}
		fmt.Fprintf(&b, "%s = %s\n", tomlKey(f.Body), tomlMultiline(a.Body))
		return []byte(b.String()), nil
	}
	return nil, fmt.Errorf("unsupported agent format %q", h.Agents.Format)
}

// modelValues returns what goes in the harness's model and effort keys. An
// inherited model writes no model key. With effort_suffix (OpenCode), the
// effort rides on the model value as a variant: opencode-go/kimi-k3#max.
func modelValues(f config.AgentFields, sel verify.Selected) (model, effort string) {
	if f.Model != "" && sel.Model != source.ModelInherit {
		model = sel.Model
	}
	if sel.Effort == "" {
		return model, ""
	}
	if f.EffortSuffix != "" {
		if model == "" {
			return "", ""
		}
		return model + f.EffortSuffix + sel.Effort, ""
	}
	if f.Effort == "" {
		return model, ""
	}
	return model, sel.Effort
}

// toolsValue maps agnostic capabilities to the harness's native tool names.
func toolsValue(reg *config.Registry, h config.Harness, a source.Agent, style string) any {
	var granted, all []string
	seenG, seenA := map[string]bool{}, map[string]bool{}
	for _, c := range reg.Capabilities { // registry order keeps output stable
		for _, t := range h.Capabilities[c] {
			if !seenA[t] {
				seenA[t] = true
				all = append(all, t)
			}
			if a.HasCap(c) && !seenG[t] {
				seenG[t] = true
				granted = append(granted, t)
			}
		}
	}
	switch style {
	case "csv":
		return strings.Join(granted, ", ")
	case "list":
		if granted == nil {
			granted = []string{}
		}
		return granted
	default: // map
		m := make(boolMap, 0, len(all))
		for _, t := range all {
			m = append(m, struct {
				K string
				V bool
			}{t, seenG[t]})
		}
		return m
	}
}

// ---------- YAML ----------

func yamlFrontmatter(pairs []kv) (string, error) {
	root := &yaml.Node{Kind: yaml.MappingNode}
	for _, p := range pairs {
		vn, err := yamlNode(p.V)
		if err != nil {
			return "", fmt.Errorf("%s: %w", p.K, err)
		}
		root.Content = append(root.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: p.K}, vn)
	}
	var buf strings.Builder
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return "", err
	}
	if err := enc.Close(); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func yamlNode(v any) (*yaml.Node, error) {
	switch x := v.(type) {
	case boolMap:
		n := &yaml.Node{Kind: yaml.MappingNode}
		for _, e := range x {
			n.Content = append(n.Content,
				&yaml.Node{Kind: yaml.ScalarNode, Value: e.K},
				&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: strconv.FormatBool(e.V)})
		}
		return n, nil
	case []string:
		n := &yaml.Node{Kind: yaml.SequenceNode}
		if len(x) == 0 {
			n.Style = yaml.FlowStyle
		}
		for _, s := range x {
			n.Content = append(n.Content, strNode(s))
		}
		return n, nil
	case []any:
		ss := make([]string, len(x))
		for i, e := range x {
			ss[i] = fmt.Sprint(e)
		}
		return yamlNode(ss)
	case string:
		return strNode(x), nil
	case bool, int, int64, float64:
		var n yaml.Node
		if err := n.Encode(x); err != nil {
			return nil, err
		}
		return &n, nil
	}
	return nil, fmt.Errorf("unsupported value type %T", v)
}

func strNode(s string) *yaml.Node {
	var n yaml.Node
	_ = n.Encode(s) // yaml.v3 picks quoting when the plain form would be ambiguous
	return &n
}

// ---------- TOML ----------

var bareKey = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func tomlKey(k string) string {
	if bareKey.MatchString(k) {
		return k
	}
	return tomlString(k)
}

func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlMultiline prefers a readable literal block; falls back to an escaped
// basic string if the body itself contains ”' or control characters.
func tomlMultiline(s string) string {
	ok := !strings.Contains(s, "'''")
	for _, r := range s {
		if (r < 0x20 && r != '\n' && r != '\t') || r == 0x7f {
			ok = false
		}
	}
	if ok && !strings.HasSuffix(s, "'") {
		return "'''\n" + s + "'''"
	}
	return tomlString(s)
}

func tomlValue(v any) (string, error) {
	switch x := v.(type) {
	case string:
		return tomlString(x), nil
	case bool:
		return strconv.FormatBool(x), nil
	case int:
		return strconv.Itoa(x), nil
	case int64:
		return strconv.FormatInt(x, 10), nil
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64), nil
	case []string:
		parts := make([]string, len(x))
		for i, s := range x {
			parts[i] = tomlString(s)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	case []any:
		ss := make([]string, len(x))
		for i, e := range x {
			ss[i] = fmt.Sprint(e)
		}
		return tomlValue(ss)
	case boolMap:
		parts := make([]string, len(x))
		for i, e := range x {
			parts[i] = tomlKey(e.K) + " = " + strconv.FormatBool(e.V)
		}
		return "{ " + strings.Join(parts, ", ") + " }", nil
	}
	return "", fmt.Errorf("unsupported value type %T", v)
}
